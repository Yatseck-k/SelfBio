            вариантов); отклонённое нигде не сохраняется, в журнале остаётся запись «bot_review». На карточке дела видны вердикт,
            проверки и шаги решения; кнопка «Перепроверить ботом» запускает проверку заново. Из консоли:
            <code>php artisan puzzles:review &lt;slug&gt;</code> или <code>--all</code> (с <code>--record</code> — с записью в журнал).
        </dd>

        <dt>Каталог предметов</dt>
        <dd>
            Раздел «Каталог предметов» (право «Каталог предметов») — редактируемые списки: виды мебели (используемые и
            неиспользуемые, значок, как говорят «на диване»), названия предметов в показаниях и мебель каждой комнаты.
            Отключённое и удалённое не попадает в новые дела. Вид, который уже стоит на картах, можно только отключить, а его
            признак «используемый» менять нельзя. Изменение отклоняется, если генератору перестало хватать данных: нужно минимум
            девять названий используемых предметов, три неиспользуемых и девять комнат.
        </dd>

        <dt>Оформление</dt>
        <dd>
            Раздел «Оформление» (то же право, что у каталога предметов) — изображения сайта. Для каждого вида мебели, находки на
            месте преступления (тело, пропажа, бокал, очаг, подлинник), печати и пола комнаты можно загрузить свой SVG (лучше),
            PNG или WebP до 60 КБ; SVG очищается от скриптов и внешних ссылок и должен иметь <code>viewBox</code>. Пустое поле
            оставляет текущее изображение, галочка «стандартное» возвращает встроенное. Здесь же редактируются подписи печатей
            («ДЕЛО ЗАКРЫТО», «НОВОЕ», «ГОСТЕВОЕ», «НОВОЕ ЗВАНИЕ») и включаются анимации (у игроков с отключённым движением в
            системе они не работают в любом случае). Изменения попадают в журнал действий.
        </dd>

        <dt>Проверка и публикация</dt>
        <dd>
            «Запустить проверку» проверяет структуру карты, авторское решение и запускает solver. Публикация возможна
            только для черновика с ровно одним решением. Результат solver: <code>unique</code> — единственное
            решение (можно публиковать), <code>zero</code> — решений нет, <code>multiple</code> — их несколько,
            <code>timeout</code> — проверка не уложилась в лимит и публикацию не разрешает.
        </dd>

        <dt>Удаление</dt>
        <dd>
            Кнопка «Удалить» (в списке и в карточке) безвозвратно удаляет дело вместе с картой, показаниями, подсказками и
            решением; запись об удалении остаётся в журнале. Будьте осторожны с опубликованными делами — они
            сразу пропадают из каталога игроков.
        </dd>
    </dl>
</div>

