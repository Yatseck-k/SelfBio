        <dt>Бот-проверяющий</dt>
        <dd>
            Перед публикацией сгенерированное дело проходит бот: он проверяет структуру и единственность решения, решает дело
            «как человек» (без перебора — только единственная клетка, перекрытие линий и «в линии осталась одна клетка»),
            следит, чтобы названные в показаниях предметы и комнаты были на карте и различимы, чтобы виновный следовал из
            правила дела, и проходит дело через публичный интерфейс (верный ответ принимается, ошибочный и неполный не
